-- Documents & Compliance is deliberately separate from the employee record.
-- Files live in a private Storage bucket; this table stores only their business
-- metadata, review state, and immutable audit events.

create table if not exists public.employee_document_types (
  id bigint generated by default as identity primary key,
  document_key text not null unique check (document_key ~ '^[a-z0-9_]+$'),
  name text not null check (nullif(btrim(name), '') is not null),
  category text not null check (category in ('hiring', 'identity', 'insurance', 'license', 'employment', 'other')),
  requires_expiry boolean not null default false,
  required_on_hire boolean not null default false,
  required_on_exit boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.employee_documents (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.employees(id) on delete restrict,
  document_type_id bigint not null references public.employee_document_types(id) on delete restrict,
  status text not null default 'received' check (status in ('missing', 'received', 'under_review', 'verified', 'rejected', 'expired', 'waived')),
  reference_number text,
  issued_on date,
  expires_on date,
  original_file_name text,
  content_type text,
  file_size_bytes bigint check (file_size_bytes is null or file_size_bytes >= 0),
  storage_path text unique,
  notes text,
  reviewed_at timestamptz,
  reviewed_by uuid references public.users(id) on delete restrict,
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null references public.users(id) on delete restrict,
  updated_by uuid references public.users(id) on delete restrict,
  check (expires_on is null or issued_on is null or expires_on >= issued_on),
  check ((status <> 'rejected') or nullif(btrim(coalesce(rejection_reason, '')), '') is not null),
  check ((status not in ('verified', 'rejected')) or (reviewed_at is not null and reviewed_by is not null))
);

create table if not exists public.employee_document_events (
  id bigint generated by default as identity primary key,
  employee_document_id uuid not null references public.employee_documents(id) on delete restrict,
  event_type text not null check (event_type in ('created', 'updated', 'file_attached', 'submitted', 'verified', 'rejected', 'waived')),
  from_status text,
  to_status text,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  created_by uuid not null references public.users(id) on delete restrict
);

create index if not exists employee_documents_employee_idx on public.employee_documents (employee_id, updated_at desc);
create index if not exists employee_documents_status_expiry_idx on public.employee_documents (status, expires_on) where expires_on is not null;
create index if not exists employee_documents_type_employee_idx on public.employee_documents (document_type_id, employee_id);
create index if not exists employee_document_events_document_idx on public.employee_document_events (employee_document_id, created_at desc);

drop trigger if exists employee_document_types_set_updated_at on public.employee_document_types;
create trigger employee_document_types_set_updated_at before update on public.employee_document_types for each row execute function public.set_updated_at();
drop trigger if exists employee_documents_set_updated_at on public.employee_documents;
create trigger employee_documents_set_updated_at before update on public.employee_documents for each row execute function public.set_updated_at();

create or replace function public.record_employee_document_event()
returns trigger language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v_event text;
begin
  if tg_op = 'INSERT' then
    insert into public.employee_document_events (employee_document_id, event_type, to_status, detail, created_by)
    values (new.id, 'created', new.status, jsonb_build_object('file_attached', new.storage_path is not null), new.created_by);
    return new;
  end if;
  v_event := case
    when new.status = 'verified' and old.status is distinct from new.status then 'verified'
    when new.status = 'rejected' and old.status is distinct from new.status then 'rejected'
    when new.status = 'waived' and old.status is distinct from new.status then 'waived'
    when new.storage_path is distinct from old.storage_path then 'file_attached'
    else 'updated'
  end;
  insert into public.employee_document_events (employee_document_id, event_type, from_status, to_status, detail, created_by)
  values (new.id, v_event, old.status, new.status, jsonb_build_object('file_attached', new.storage_path is not null), new.updated_by);
  return new;
end;
$$;

