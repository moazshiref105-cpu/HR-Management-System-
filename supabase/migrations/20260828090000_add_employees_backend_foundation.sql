-- Employees backend foundation. SetUp remains the sole source for lookup data.

create table public.employees (
  id uuid primary key default gen_random_uuid(),
  employee_number bigint not null unique,
  employee_status text not null default 'active' check (employee_status in ('active', 'resigned', 'inactive')),
  employee_classification text not null default 'standard' check (employee_classification in ('standard', 'five_percent')),
  gender text not null check (gender in ('male', 'female')),
  arabic_full_name text not null check (nullif(btrim(arabic_full_name), '') is not null),
  english_full_name text not null check (nullif(btrim(english_full_name), '') is not null),
  identity_card_number text not null unique check (identity_card_number ~ '^[0-9]{14}$'),
  identity_card_expiration_date date not null,
  date_of_birth date not null check (date_of_birth <= current_date),
  religion_id bigint not null references public.religions(id) on delete restrict,
  marital_status_id bigint not null references public.marital_statuses(id) on delete restrict,
  diploma_id bigint references public.diplomas(id) on delete restrict,
  major text,
  graduated_from text,
  phone text not null check (phone ~ '^[0-9]{11}$'),
  governorate_id bigint not null references public.governorates(id) on delete restrict,
  address text,
  department_id bigint not null references public.departments(id) on delete restrict,
  shift_type_id bigint not null references public.shift_types(id) on delete restrict,
  team_id bigint references public.teams(id) on delete restrict,
  position_id bigint not null references public.positions(id) on delete restrict,
  project_id bigint references public.projects(id) on delete restrict,
  joining_date date not null,
  contract_signing_date date not null,
  contract_expiration_date date generated always as ((contract_signing_date + interval '1 year - 1 day')::date) stored,
  probation_due_date date generated always as ((joining_date + interval '3 months - 1 day')::date) stored,
  social_insurance_active boolean not null default false,
  social_insurance_comment text,
  form_1_incoming_number text,
  form_1_incoming_date date,
  bank_id bigint references public.banks(id) on delete restrict,
  leaving_date date,
  leaving_reason_id bigint references public.leaving_reasons(id) on delete restrict,
  leaving_comment text,
  annual_days_settled numeric(8,2) check (annual_days_settled is null or annual_days_settled >= 0),
  form_6_incoming_number text,
  form_6_incoming_date date,
  form_6_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null references public.users(id) on delete restrict,
  updated_by uuid references public.users(id) on delete restrict,
  check (contract_signing_date >= joining_date),
  check (employee_status = 'active' or (leaving_date is not null and leaving_reason_id is not null))
);

create table public.employee_wives (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employees(id) on delete restrict,
  wife_name text not null check (nullif(btrim(wife_name), '') is not null),
  identity_card_number text not null check (identity_card_number ~ '^[0-9]{14}$'),
  is_working boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null references public.users(id) on delete restrict,
  updated_by uuid references public.users(id) on delete restrict,
  unique (employee_id, identity_card_number)
);

create table public.employee_children (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employees(id) on delete restrict,
  wife_id bigint references public.employee_wives(id) on delete restrict,
  child_name text not null check (nullif(btrim(child_name), '') is not null),
  identity_card_number text not null check (identity_card_number ~ '^[0-9]{14}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null references public.users(id) on delete restrict,
  updated_by uuid references public.users(id) on delete restrict,
  unique (employee_id, identity_card_number)
);

create table public.employee_licenses (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employees(id) on delete restrict,
  license_type_id bigint not null references public.license_types(id) on delete restrict,
  release_date date not null,
  expiry_date date not null check (expiry_date >= release_date),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null references public.users(id) on delete restrict,
  updated_by uuid references public.users(id) on delete restrict
);

create table public.employee_contract_renewals (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employees(id) on delete restrict,
  previous_contract_signing_date date not null,
  previous_contract_expiration_date date not null,
  renewal_signing_date date not null,
  renewal_expiration_date date not null,
  created_at timestamptz not null default now(),
  created_by uuid not null references public.users(id) on delete restrict,
  check (renewal_expiration_date = (renewal_signing_date + interval '1 year - 1 day')::date)
);

create table public.employee_notifications (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employees(id) on delete restrict,
  notification_type text not null check (notification_type in ('identity_card_expiry', 'license_expiry', 'form_1_deadline', 'medical_insurance_eligibility', 'life_insurance_eligibility')),
  -- Zero represents an employee-level source; license reminders use the license ID.
  -- Non-null is required so the uniqueness guarantee remains effective in PostgreSQL.
  source_id bigint not null default 0,
  due_date date not null,
  reminder_threshold_days integer not null check (reminder_threshold_days >= 0),
  reference_key text not null,
  deep_link text not null,
  status text not null default 'open' check (status in ('open', 'read', 'dismissed', 'resolved')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (employee_id, notification_type, source_id, reminder_threshold_days)
);

