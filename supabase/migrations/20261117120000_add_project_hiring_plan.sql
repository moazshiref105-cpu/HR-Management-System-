create or replace function public.project_hiring_plan_staffing(
  p_project_id bigint default null,
  p_department_id bigint default null,
  p_position_id bigint default null,
  p_status text default null,
  p_search text default null,
  p_page integer default 1,
  p_page_size integer default 25
)
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, public, pg_temp
as $$
  with plan_rows as (
    select hp.id, hp.project_id, pr.name project_name,
      hp.department_id, d.name department_name,
      hp.position_id, po.name position_name, po.position_code,
      hp.planned_count,
      count(e.id)::integer actual_count,
      count(e.id)::integer - hp.planned_count difference,
      case when count(e.id) = hp.planned_count then 'complete'
        when count(e.id) < hp.planned_count then 'under_plan' else 'over_plan' end status
    from public.project_hiring_plans hp
    join public.projects pr on pr.id=hp.project_id
    join public.departments d on d.id=hp.department_id
    join public.positions po on po.id=hp.position_id
    left join public.employees e on e.project_id=hp.project_id
      and e.department_id=hp.department_id and e.position_id=hp.position_id
      and e.employee_status='active'
    where (p_project_id is null or hp.project_id=p_project_id)
      and (p_department_id is null or hp.department_id=p_department_id)
      and (p_position_id is null or hp.position_id=p_position_id)
    group by hp.id,pr.name,d.name,po.name,po.position_code
  ), filtered as (
    select * from plan_rows r
    where (p_status is null or p_status='' or r.status=p_status)
      and (p_search is null or btrim(p_search)='' or
        concat_ws(' ',r.project_name,r.department_name,r.position_name,r.position_code) ilike '%'||btrim(p_search)||'%')
  ), page_rows as (
    select * from filtered order by project_name,department_name,position_name,id
    limit least(greatest(coalesce(p_page_size,25),1),100)
    offset (greatest(coalesce(p_page,1),1)-1)*least(greatest(coalesce(p_page_size,25),1),100)
  ), assignment_review as (
    select count(*)::integer count
    from public.employees e
    left join public.projects pr on pr.id=e.project_id
    left join public.departments d on d.id=e.department_id
    left join public.positions po on po.id=e.position_id
    where e.employee_status='active'
      and (e.project_id is null or pr.is_active is distinct from true
        or e.department_id is null or d.is_active is distinct from true
        or e.position_id is null or po.is_active is distinct from true
        or not exists(select 1 from public.project_hiring_plans hp where hp.project_id=e.project_id and hp.department_id=e.department_id and hp.position_id=e.position_id))
  )
  select jsonb_build_object(
    'rows',coalesce((select jsonb_agg(to_jsonb(p)) from page_rows p),'[]'::jsonb),
    'pagination',jsonb_build_object(
      'page',greatest(coalesce(p_page,1),1),
      'page_size',least(greatest(coalesce(p_page_size,25),1),100),
      'total',(select count(*) from filtered),
      'total_pages',ceil((select count(*) from filtered)::numeric/least(greatest(coalesce(p_page_size,25),1),100)),
      'has_previous',greatest(coalesce(p_page,1),1)>1,
      'has_next',greatest(coalesce(p_page,1),1)<ceil((select count(*) from filtered)::numeric/least(greatest(coalesce(p_page_size,25),1),100))
    ),
    'totals',jsonb_build_object(
      'planned',coalesce((select sum(planned_count) from filtered),0),
      'actual',coalesce((select sum(actual_count) from filtered),0),
      'vacant',coalesce((select sum(greatest(planned_count-actual_count,0)) from filtered),0),
      'excess',coalesce((select sum(greatest(actual_count-planned_count,0)) from filtered),0)
    ),
    'assignment_review_count',(select count from assignment_review)
  );
$$;

create or replace function public.project_hiring_plan_employees(
  p_plan_id bigint,
  p_page integer default 1,
  p_page_size integer default 25
)
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, public, pg_temp
as $$
  with scope as (
    select project_id,department_id,position_id from public.project_hiring_plans where id=p_plan_id
  ), active_employees as (
    select e.id,e.employee_number,e.arabic_full_name,e.english_full_name,e.employee_classification,e.joining_date
    from public.employees e join scope s on e.project_id=s.project_id
      and e.department_id=s.department_id and e.position_id=s.position_id
    where e.employee_status='active'
  ), page_rows as (
    select * from active_employees order by employee_number,id
    limit least(greatest(coalesce(p_page_size,25),1),100)
    offset (greatest(coalesce(p_page,1),1)-1)*least(greatest(coalesce(p_page_size,25),1),100)
  )
  select jsonb_build_object(
    'rows',coalesce((select jsonb_agg(to_jsonb(p)) from page_rows p),'[]'::jsonb),
    'pagination',jsonb_build_object(
      'page',greatest(coalesce(p_page,1),1),
      'page_size',least(greatest(coalesce(p_page_size,25),1),100),
      'total',(select count(*) from active_employees),
      'total_pages',ceil((select count(*) from active_employees)::numeric/least(greatest(coalesce(p_page_size,25),1),100)),
      'has_previous',greatest(coalesce(p_page,1),1)>1,
      'has_next',greatest(coalesce(p_page,1),1)<ceil((select count(*) from active_employees)::numeric/least(greatest(coalesce(p_page_size,25),1),100))
    )
  );
$$;

create or replace function public.project_hiring_plan_assignment_review(
  p_page integer default 1,
  p_page_size integer default 25,
  p_search text default null
)
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, public, pg_temp
as $$
  with review_rows as (
    select e.id,e.employee_number,e.arabic_full_name,e.english_full_name,
      e.project_id,pr.name project_name,e.department_id,d.name department_name,
      e.position_id,po.name position_name,
      array_remove(array[
        case when e.project_id is null then 'No project' when pr.is_active is distinct from true then 'Inactive project' end,
        case when e.department_id is null then 'No department' when d.is_active is distinct from true then 'Inactive department' end,
        case when e.position_id is null then 'No position' when po.is_active is distinct from true then 'Inactive position' end,
        case when e.project_id is not null and e.department_id is not null and e.position_id is not null
          and not exists(select 1 from public.project_hiring_plans hp where hp.project_id=e.project_id and hp.department_id=e.department_id and hp.position_id=e.position_id)
          then 'No matching hiring plan' end
      ],null) assignment_issues
    from public.employees e
    left join public.projects pr on pr.id=e.project_id
    left join public.departments d on d.id=e.department_id
    left join public.positions po on po.id=e.position_id
    where e.employee_status='active'
      and (e.project_id is null or pr.is_active is distinct from true
        or e.department_id is null or d.is_active is distinct from true
        or e.position_id is null or po.is_active is distinct from true
        or not exists(select 1 from public.project_hiring_plans hp where hp.project_id=e.project_id and hp.department_id=e.department_id and hp.position_id=e.position_id))
      and (p_search is null or btrim(p_search)='' or e.employee_number::text ilike '%'||btrim(p_search)||'%'
        or e.arabic_full_name ilike '%'||btrim(p_search)||'%' or e.english_full_name ilike '%'||btrim(p_search)||'%')
  ), page_rows as (
    select * from review_rows order by employee_number,id
    limit least(greatest(coalesce(p_page_size,25),1),100)
    offset (greatest(coalesce(p_page,1),1)-1)*least(greatest(coalesce(p_page_size,25),1),100)
  )
  select jsonb_build_object(
    'rows',coalesce((select jsonb_agg(to_jsonb(p)) from page_rows p),'[]'::jsonb),
    'pagination',jsonb_build_object(
      'page',greatest(coalesce(p_page,1),1),
      'page_size',least(greatest(coalesce(p_page_size,25),1),100),
      'total',(select count(*) from review_rows),
      'total_pages',ceil((select count(*) from review_rows)::numeric/least(greatest(coalesce(p_page_size,25),1),100)),
      'has_previous',greatest(coalesce(p_page,1),1)>1,
      'has_next',greatest(coalesce(p_page,1),1)<ceil((select count(*) from review_rows)::numeric/least(greatest(coalesce(p_page_size,25),1),100))
    )
  );
$$;

