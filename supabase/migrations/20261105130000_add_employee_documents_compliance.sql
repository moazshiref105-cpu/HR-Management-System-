-- Browser uploads use Storage with the caller's Supabase session; metadata and
-- review remain server-owned and are always permission checked by DocumentApi.
drop policy if exists employee_documents_storage_read on storage.objects;
create policy employee_documents_storage_read on storage.objects for select to authenticated
using (bucket_id = 'employee-documents' and exists (
  select 1 from public.users u where u.auth_user_id = auth.uid() and u.is_active
    and (u.is_super_admin or public.user_has_permission(u.id, 'employees.documents.view'))
));
drop policy if exists employee_documents_storage_insert on storage.objects;
create policy employee_documents_storage_insert on storage.objects for insert to authenticated
with check (bucket_id = 'employee-documents' and exists (
  select 1 from public.users u where u.auth_user_id = auth.uid() and u.is_active
    and (u.is_super_admin or public.user_has_permission(u.id, 'employees.documents.edit'))
));
drop policy if exists employee_documents_storage_update on storage.objects;
create policy employee_documents_storage_update on storage.objects for update to authenticated
using (bucket_id = 'employee-documents' and exists (
  select 1 from public.users u where u.auth_user_id = auth.uid() and u.is_active
    and (u.is_super_admin or public.user_has_permission(u.id, 'employees.documents.edit'))
));

revoke all on function public.record_employee_document_event() from public, anon, authenticated;
