create or replace function public.assign_employee_number()
returns trigger language plpgsql as $$
begin
  if new.employee_number is not null then
    raise exception 'Employee ID is generated by the system';
  end if;
  perform pg_advisory_xact_lock(pg_catalog.hashtext('hms.employee_number'));
  select coalesce(max(employee_number), 0) + 1 into new.employee_number from public.employees;
  return new;
end;
$$;

create or replace function public.prevent_employee_number_change()
returns trigger language plpgsql as $$
begin
  if new.employee_number <> old.employee_number then
    raise exception 'Employee ID is immutable';
  end if;
  return new;
end;
$$;

create or replace function public.ensure_child_wife_belongs_to_employee()
returns trigger language plpgsql as $$
begin
  if new.wife_id is not null and not exists (
    select 1 from public.employee_wives where id = new.wife_id and employee_id = new.employee_id
  ) then
    raise exception 'Child wife must belong to the same employee';
  end if;
  return new;
end;
$$;

create or replace function public.refresh_employee_notifications(p_employee_id uuid, p_as_of date default current_date)
returns void language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v_employee public.employees%rowtype;
  v_medical_months integer;
  v_life_months integer;
  v_form_1_deadline date;
begin
  select * into v_employee from public.employees where id = p_employee_id;
  if not found then raise exception 'Employee does not exist'; end if;
  select value::integer into v_medical_months from public.insurance_settings where setting_key = 'medical_insurance_eligibility_months' and is_active;
  select value::integer into v_life_months from public.insurance_settings where setting_key = 'life_insurance_eligibility_months' and is_active;
  v_form_1_deadline := (v_employee.contract_signing_date + interval '1 month')::date;

  insert into public.employee_notifications (employee_id, notification_type, source_id, due_date, reminder_threshold_days, reference_key, deep_link)
  select v_employee.id, 'identity_card_expiry', 0, v_employee.identity_card_expiration_date, threshold_days, 'personal.identity_card_expiration_date', '/employees/' || v_employee.id || '#identity-card'
  from unnest(array[30, 14, 7]) as threshold_days
  where case threshold_days
    when 30 then (v_employee.identity_card_expiration_date - interval '1 month')::date
    else v_employee.identity_card_expiration_date - threshold_days
  end <= p_as_of
  on conflict (employee_id, notification_type, source_id, reminder_threshold_days) do update
    set due_date = excluded.due_date, updated_at = now()
    where employee_notifications.status = 'open';

  insert into public.employee_notifications (employee_id, notification_type, source_id, due_date, reminder_threshold_days, reference_key, deep_link)
  select l.employee_id, 'license_expiry', l.id, l.expiry_date, threshold_days, 'licenses.' || l.id, '/employees/' || l.employee_id || '#licenses'
  from public.employee_licenses l cross join unnest(array[30, 14, 7]) as threshold_days
  where l.employee_id = v_employee.id and case threshold_days
    when 30 then (l.expiry_date - interval '1 month')::date
    else l.expiry_date - threshold_days
  end <= p_as_of
  on conflict (employee_id, notification_type, source_id, reminder_threshold_days) do update
    set due_date = excluded.due_date, updated_at = now()
    where employee_notifications.status = 'open';

  insert into public.employee_notifications (employee_id, notification_type, source_id, due_date, reminder_threshold_days, reference_key, deep_link)
  select v_employee.id, 'form_1_deadline', 0, v_form_1_deadline, threshold_days, 'insurance.form_1_incoming_date', '/employees/' || v_employee.id || '#form-1'
  from unnest(array[21, 7]) as threshold_days
  where v_employee.form_1_incoming_date is null and v_form_1_deadline - threshold_days <= p_as_of
  on conflict (employee_id, notification_type, source_id, reminder_threshold_days) do update
    set due_date = excluded.due_date, updated_at = now()
    where employee_notifications.status = 'open';

  insert into public.employee_notifications (employee_id, notification_type, source_id, due_date, reminder_threshold_days, reference_key, deep_link)
  select v_employee.id, 'medical_insurance_eligibility', 0, (v_employee.joining_date + make_interval(months => coalesce(v_medical_months, 0)))::date, 0, 'insurance.medical', '/employees/' || v_employee.id || '#medical-insurance'
  where (v_employee.joining_date + make_interval(months => coalesce(v_medical_months, 0)))::date <= p_as_of
  on conflict (employee_id, notification_type, source_id, reminder_threshold_days) do update set due_date = excluded.due_date, updated_at = now() where employee_notifications.status = 'open';

  insert into public.employee_notifications (employee_id, notification_type, source_id, due_date, reminder_threshold_days, reference_key, deep_link)
  select v_employee.id, 'life_insurance_eligibility', 0, (v_employee.joining_date + make_interval(months => coalesce(v_life_months, 0)))::date, 0, 'insurance.life', '/employees/' || v_employee.id || '#life-insurance'
  where (v_employee.joining_date + make_interval(months => coalesce(v_life_months, 0)))::date <= p_as_of
  on conflict (employee_id, notification_type, source_id, reminder_threshold_days) do update set due_date = excluded.due_date, updated_at = now() where employee_notifications.status = 'open';

  if v_employee.form_1_incoming_date is not null then
    update public.employee_notifications
    set status = 'resolved', updated_at = now()
    where employee_id = v_employee.id and notification_type = 'form_1_deadline' and status = 'open';
  end if;
end;
$$;

create or replace function public.renew_employee_contract(p_employee_id uuid, p_renewal_signing_date date, p_actor_id uuid)
returns public.employee_contract_renewals language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v_employee public.employees%rowtype;
  v_renewal public.employee_contract_renewals%rowtype;
begin
  select * into v_employee from public.employees where id = p_employee_id for update;
  if not found then raise exception 'Employee does not exist'; end if;
  if p_renewal_signing_date is null or p_renewal_signing_date < v_employee.joining_date then
    raise exception 'Renewal signing date must be on or after joining date';
  end if;
  insert into public.employee_contract_renewals (
    employee_id, previous_contract_signing_date, previous_contract_expiration_date,
    renewal_signing_date, renewal_expiration_date, created_by
  ) values (
    v_employee.id, v_employee.contract_signing_date, v_employee.contract_expiration_date,
    p_renewal_signing_date, (p_renewal_signing_date + interval '1 year - 1 day')::date, p_actor_id
  ) returning * into v_renewal;
  update public.employees set contract_signing_date = p_renewal_signing_date, updated_by = p_actor_id where id = p_employee_id;
  return v_renewal;
end;
$$;

