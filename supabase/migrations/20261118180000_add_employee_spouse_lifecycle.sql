-- Retain spouse records after divorce/death or data correction. Lifecycle
-- changes are performed through the RPCs below so employee status and history
-- are committed atomically. Existing spouse and child rows are not rewritten.

alter table public.marital_statuses
  add column if not exists is_divorced_status boolean not null default false,
  add column if not exists is_widowed_status boolean not null default false;

do $$
declare
  v_count integer;
  v_id bigint;
  v_married_marker_count integer;
  v_exact_married_marker_count integer;
begin
  select count(*), count(*) filter (where lower(btrim(name)) = 'married')
    into v_married_marker_count, v_exact_married_marker_count
  from public.marital_statuses where is_married_status;
  if v_married_marker_count <> 1 or v_exact_married_marker_count <> 1 then
    raise exception 'HMS_MARRIED_STATUS_MARKER_INVALID: expected exactly one system marker on the exact normalized Married lookup row.';
  end if;

  select count(*), min(id) into v_count, v_id
  from public.marital_statuses where lower(btrim(name)) = 'divorced';
  if v_count > 1 then raise exception 'HMS_DIVORCED_STATUS_AMBIGUOUS: multiple exact Divorced lookup rows exist.'; end if;
  if v_count = 0 then
    insert into public.marital_statuses(name, description, is_active, is_divorced_status)
    values ('Divorced', 'Employee marital status after a marriage ends by divorce.', true, true);
  else
    update public.marital_statuses set is_divorced_status = true where id = v_id;
  end if;

  select count(*), min(id) into v_count, v_id
  from public.marital_statuses where lower(btrim(name)) = 'widowed';
  if v_count > 1 then raise exception 'HMS_WIDOWED_STATUS_AMBIGUOUS: multiple exact Widowed lookup rows exist.'; end if;
  if v_count = 0 then
    insert into public.marital_statuses(name, description, is_active, is_widowed_status)
    values ('Widowed', 'Employee marital status after a spouse has died.', true, true);
  else
    update public.marital_statuses set is_widowed_status = true where id = v_id;
  end if;
end;
$$;

create unique index if not exists marital_statuses_single_divorced_marker_idx
  on public.marital_statuses (is_divorced_status) where is_divorced_status;
create unique index if not exists marital_statuses_single_widowed_marker_idx
  on public.marital_statuses (is_widowed_status) where is_widowed_status;

alter table public.employee_wives
  add column if not exists relationship_status text not null default 'current',
  add column if not exists relationship_end_date date,
  add column if not exists marriage_end_reason text,
  add column if not exists correction_reason text;

alter table public.employee_wives
  add constraint employee_wives_relationship_status_check
    check (relationship_status in ('current', 'former', 'void')),
  add constraint employee_wives_lifecycle_fields_check check (
    (relationship_status = 'current' and relationship_end_date is null and marriage_end_reason is null and correction_reason is null)
    or (relationship_status = 'former' and relationship_end_date is not null and marriage_end_reason in ('divorce', 'death') and correction_reason is null)
    or (relationship_status = 'void' and relationship_end_date is null and marriage_end_reason is null and nullif(btrim(correction_reason), '') is not null)
  );
create index if not exists employee_wives_current_by_employee_idx
  on public.employee_wives(employee_id) where relationship_status = 'current';

create table public.employee_wife_lifecycle_events (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employees(id) on delete restrict,
  spouse_id bigint not null references public.employee_wives(id) on delete restrict,
  actor_id uuid not null references public.users(id) on delete restrict,
  action text not null check (action in ('marriage_ended', 'record_corrected')),
  occurred_at timestamptz not null default now(),
  effective_date date,
  reason_code text,
  reason_text text not null,
  previous_state text not null check (previous_state in ('current', 'former')),
  new_state text not null check (new_state in ('former', 'void')),
  check ((action = 'marriage_ended' and new_state = 'former' and effective_date is not null and reason_code in ('divorce', 'death'))
      or (action = 'record_corrected' and new_state = 'void' and effective_date is null and reason_code is null))
);
create index employee_wife_lifecycle_events_spouse_idx
  on public.employee_wife_lifecycle_events(spouse_id, occurred_at desc);
create index employee_wife_lifecycle_events_employee_idx
  on public.employee_wife_lifecycle_events(employee_id, occurred_at desc);
alter table public.employee_wife_lifecycle_events enable row level security;
revoke all on public.employee_wife_lifecycle_events from public, anon, authenticated;
revoke insert, update, delete, truncate, references, trigger on public.employee_wife_lifecycle_events from service_role;
grant select on public.employee_wife_lifecycle_events to service_role;
revoke all on sequence public.employee_wife_lifecycle_events_id_seq from public, anon, authenticated, service_role;

comment on column public.employee_wives.relationship_status is 'current, former, or void; spouse rows are retained so child relationships remain intact.';
comment on column public.marital_statuses.is_divorced_status is 'System-managed marker for the canonical Divorced lookup row.';
comment on column public.marital_statuses.is_widowed_status is 'System-managed marker for the canonical Widowed lookup row.';
comment on table public.employee_wife_lifecycle_events is 'Append-only history of spouse marriage end and erroneous-record correction actions.';

create or replace function public.guard_employee_wife_lifecycle()
returns trigger language plpgsql set search_path = pg_catalog, public, pg_temp as $$
begin
  if tg_op = 'INSERT' and new.relationship_status <> 'current' then
    raise exception 'HMS_SPOUSE_LIFECYCLE_INSERT_INVALID: spouse records must be created as current.';
  end if;
  if tg_op = 'UPDATE' and old.relationship_status = 'void'
    and (old.wife_name is distinct from new.wife_name
      or old.identity_card_number is distinct from new.identity_card_number
      or old.is_working is distinct from new.is_working) then
    raise exception 'HMS_SPOUSE_CORRECTED_RECORD_IMMUTABLE: corrected spouse records are retained as immutable history.';
  end if;
  if tg_op = 'UPDATE' and old.employee_id is distinct from new.employee_id then
    raise exception 'HMS_SPOUSE_EMPLOYEE_LINK_IMMUTABLE: spouse records cannot be moved between employees.';
  end if;
  if tg_op = 'UPDATE' and old.relationship_status is not distinct from new.relationship_status
    and (old.relationship_end_date is distinct from new.relationship_end_date
      or old.marriage_end_reason is distinct from new.marriage_end_reason
      or old.correction_reason is distinct from new.correction_reason) then
    raise exception 'HMS_SPOUSE_LIFECYCLE_FIELDS_REQUIRE_TRANSITION: use the spouse lifecycle workflow to change lifecycle details.';
  end if;
  if tg_op = 'UPDATE' and old.employee_id is distinct from new.employee_id then
    raise exception 'HMS_SPOUSE_EMPLOYEE_LINK_IMMUTABLE: spouse records cannot be moved between employees.';
  end if;
  if tg_op = 'UPDATE' and old.relationship_status is not distinct from new.relationship_status
    and (old.relationship_end_date is distinct from new.relationship_end_date
      or old.marriage_end_reason is distinct from new.marriage_end_reason
      or old.correction_reason is distinct from new.correction_reason) then
    raise exception 'HMS_SPOUSE_LIFECYCLE_FIELDS_REQUIRE_TRANSITION: use the spouse lifecycle workflow to change lifecycle details.';
  end if;
  if tg_op = 'UPDATE' and old.relationship_status is distinct from new.relationship_status then
    if old.relationship_status = 'void'
      or not ((old.relationship_status = 'current' and new.relationship_status in ('former', 'void'))
        or (old.relationship_status = 'former' and new.relationship_status = 'void')) then
      raise exception 'HMS_SPOUSE_LIFECYCLE_TRANSITION_INVALID: this spouse state transition is not allowed.';
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists employee_wives_guard_lifecycle on public.employee_wives;
create trigger employee_wives_guard_lifecycle before insert or update on public.employee_wives
for each row execute function public.guard_employee_wife_lifecycle();

create or replace function public.audit_employee_wife_lifecycle()
returns trigger language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
begin
  if old.relationship_status is distinct from new.relationship_status then
    insert into public.employee_wife_lifecycle_events(
      employee_id, spouse_id, actor_id, action, effective_date, reason_code,
      reason_text, previous_state, new_state
    ) values (
      new.employee_id, new.id, coalesce(new.updated_by, new.created_by),
      case when new.relationship_status = 'former' then 'marriage_ended' else 'record_corrected' end,
      new.relationship_end_date, new.marriage_end_reason,
      case when new.relationship_status = 'former' then 'Marriage ended: ' || new.marriage_end_reason else new.correction_reason end,
      old.relationship_status, new.relationship_status
    );
  end if;
  return new;
end;
$$;
revoke all on function public.audit_employee_wife_lifecycle() from public, anon, authenticated;
grant execute on function public.audit_employee_wife_lifecycle() to service_role;
drop trigger if exists employee_wives_audit_lifecycle on public.employee_wives;
create trigger employee_wives_audit_lifecycle after update on public.employee_wives
for each row execute function public.audit_employee_wife_lifecycle();

-- Replace the prior trigger body without changing its trigger identity. Only a
-- current spouse implies Married; ending/correcting the last spouse leaves the
-- employee status to the explicit lifecycle RPC below.
create or replace function public.mark_employee_married_for_spouse()
returns trigger language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v_match_count integer;
  v_married_status_id bigint;
begin
  if exists (select 1 from public.employee_wives spouse where spouse.employee_id = new.employee_id and spouse.relationship_status = 'current') then
    select count(*), min(id) into v_match_count, v_married_status_id
    from public.marital_statuses where is_married_status = true;
    if v_match_count <> 1 then
      raise exception 'HMS_MARRIED_STATUS_MARKER_INVALID: expected exactly one marked Married status, found %.', v_match_count;
    end if;
    update public.employees employee
    set marital_status_id = v_married_status_id,
        updated_by = coalesce(new.updated_by, employee.updated_by)
    where employee.id = new.employee_id and employee.marital_status_id is distinct from v_married_status_id;
  end if;
  return new;
end;
$$;
revoke all on function public.mark_employee_married_for_spouse() from public, anon, authenticated;
grant execute on function public.mark_employee_married_for_spouse() to service_role;

-- Keep the implication true if an employee edit attempts to select another
-- status while a current spouse exists. Ending the last spouse first removes
-- that condition, allowing its RPC to apply the explicit resulting status.
create or replace function public.enforce_married_for_employee_with_current_spouse()
returns trigger language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v_match_count integer;
  v_married_status_id bigint;
begin
  if exists (select 1 from public.employee_wives spouse where spouse.employee_id = new.id and spouse.relationship_status = 'current') then
    select count(*), min(id) into v_match_count, v_married_status_id
    from public.marital_statuses where is_married_status = true;
    if v_match_count <> 1 then
      raise exception 'HMS_MARRIED_STATUS_MARKER_INVALID: expected exactly one marked Married status, found %.', v_match_count;
    end if;
    new.marital_status_id := v_married_status_id;
  end if;
  return new;
end;
$$;
revoke all on function public.enforce_married_for_employee_with_current_spouse() from public, anon, authenticated;
grant execute on function public.enforce_married_for_employee_with_current_spouse() to service_role;
drop trigger if exists employees_current_spouse_married_guard on public.employees;
create trigger employees_current_spouse_married_guard
before insert or update of marital_status_id on public.employees
for each row execute function public.enforce_married_for_employee_with_current_spouse();

create or replace function public.end_employee_wife_marriage(
  p_employee_id uuid, p_spouse_id bigint, p_expected_updated_at timestamptz,
  p_effective_date date, p_end_reason text, p_resulting_marital_status_id bigint,
  p_actor_id uuid
) returns jsonb language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v_spouse public.employee_wives%rowtype;
  v_current_count integer;
  v_marker_count integer;
  v_expected_status_id bigint;
  v_expected_status_active boolean;
  v_expected_status_is_married boolean;
begin
  if p_actor_id is null or not exists(select 1 from public.users where id = p_actor_id) then raise exception 'HMS_ACTOR_REQUIRED'; end if;
  if p_effective_date is null or p_end_reason is null or p_end_reason not in ('divorce', 'death') then raise exception 'HMS_SPOUSE_END_DETAILS_REQUIRED'; end if;
  perform 1 from public.employees where id = p_employee_id for update;
  if not found then raise exception 'HMS_EMPLOYEE_NOT_FOUND'; end if;
  select * into v_spouse from public.employee_wives where id = p_spouse_id and employee_id = p_employee_id for update;
  if not found then raise exception 'HMS_SPOUSE_NOT_FOUND'; end if;
  if v_spouse.updated_at is distinct from p_expected_updated_at then raise exception 'HMS_SPOUSE_STALE_VERSION'; end if;
  if v_spouse.relationship_status <> 'current' then raise exception 'HMS_SPOUSE_NOT_CURRENT'; end if;

  update public.employee_wives set relationship_status = 'former', relationship_end_date = p_effective_date,
    marriage_end_reason = p_end_reason, correction_reason = null, updated_by = p_actor_id
  where id = p_spouse_id;
  select count(*) into v_current_count from public.employee_wives where employee_id = p_employee_id and relationship_status = 'current';
  if v_current_count > 0 then
    if p_resulting_marital_status_id is not null then raise exception 'HMS_RESULTING_STATUS_NOT_APPLICABLE'; end if;
    return jsonb_build_object('employee_id', p_employee_id, 'spouse_id', p_spouse_id, 'relationship_status', 'former', 'current_spouse_count', v_current_count);
  end if;
  if p_resulting_marital_status_id is null then raise exception 'HMS_RESULTING_STATUS_REQUIRED'; end if;
  if p_end_reason = 'divorce' then
    select count(*), min(id), bool_or(is_active), bool_or(is_married_status)
      into v_marker_count, v_expected_status_id, v_expected_status_active, v_expected_status_is_married
    from public.marital_statuses where is_divorced_status = true;
  else
    select count(*), min(id), bool_or(is_active), bool_or(is_married_status)
      into v_marker_count, v_expected_status_id, v_expected_status_active, v_expected_status_is_married
    from public.marital_statuses where is_widowed_status = true;
  end if;
  if v_marker_count = 0 then raise exception 'HMS_RESULTING_STATUS_MARKER_MISSING'; end if;
  if v_marker_count > 1 then raise exception 'HMS_RESULTING_STATUS_MARKER_AMBIGUOUS'; end if;
  if not coalesce(v_expected_status_active, false) then raise exception 'HMS_RESULTING_STATUS_MARKER_INACTIVE'; end if;
  if coalesce(v_expected_status_is_married, true) then raise exception 'HMS_RESULTING_STATUS_MARKER_INVALID'; end if;
  if p_resulting_marital_status_id is distinct from v_expected_status_id then
    raise exception 'HMS_RESULTING_STATUS_REASON_MISMATCH';
  end if;
  update public.employees set marital_status_id = p_resulting_marital_status_id, updated_by = p_actor_id where id = p_employee_id;
  return jsonb_build_object('employee_id', p_employee_id, 'spouse_id', p_spouse_id, 'relationship_status', 'former', 'current_spouse_count', 0, 'marital_status_id', p_resulting_marital_status_id);
end;
$$;

create or replace function public.correct_employee_wife_record(
  p_employee_id uuid, p_spouse_id bigint, p_expected_updated_at timestamptz,
  p_correction_reason text, p_resulting_marital_status_id bigint,
  p_actor_id uuid
) returns jsonb language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v_spouse public.employee_wives%rowtype;
  v_current_count integer;
  v_status_exists boolean;
begin
  if p_actor_id is null or not exists(select 1 from public.users where id = p_actor_id) then raise exception 'HMS_ACTOR_REQUIRED'; end if;
  if nullif(btrim(p_correction_reason), '') is null or length(p_correction_reason) > 2000 then raise exception 'HMS_CORRECTION_REASON_REQUIRED'; end if;
  perform 1 from public.employees where id = p_employee_id for update;
  if not found then raise exception 'HMS_EMPLOYEE_NOT_FOUND'; end if;
  select * into v_spouse from public.employee_wives where id = p_spouse_id and employee_id = p_employee_id for update;
  if not found then raise exception 'HMS_SPOUSE_NOT_FOUND'; end if;
  if v_spouse.updated_at is distinct from p_expected_updated_at then raise exception 'HMS_SPOUSE_STALE_VERSION'; end if;
  if v_spouse.relationship_status = 'void' then raise exception 'HMS_SPOUSE_ALREADY_CORRECTED'; end if;

  update public.employee_wives set relationship_status = 'void', relationship_end_date = null,
    marriage_end_reason = null, correction_reason = btrim(p_correction_reason), updated_by = p_actor_id
  where id = p_spouse_id;
  select count(*) into v_current_count from public.employee_wives where employee_id = p_employee_id and relationship_status = 'current';
  if v_spouse.relationship_status = 'current' and v_current_count = 0 then
    if p_resulting_marital_status_id is null then raise exception 'HMS_RESULTING_STATUS_REQUIRED'; end if;
    select exists(select 1 from public.marital_statuses where id = p_resulting_marital_status_id and is_active and not is_married_status) into v_status_exists;
    if not v_status_exists then raise exception 'HMS_RESULTING_STATUS_INVALID'; end if;
    update public.employees set marital_status_id = p_resulting_marital_status_id, updated_by = p_actor_id where id = p_employee_id;
  elsif p_resulting_marital_status_id is not null then
    raise exception 'HMS_RESULTING_STATUS_NOT_APPLICABLE';
  end if;
  return jsonb_build_object('employee_id', p_employee_id, 'spouse_id', p_spouse_id, 'relationship_status', 'void', 'current_spouse_count', v_current_count, 'marital_status_id', case when p_resulting_marital_status_id is not null then p_resulting_marital_status_id else null end);
end;
$$;

revoke all on function public.end_employee_wife_marriage(uuid,bigint,timestamptz,date,text,bigint,uuid) from public, anon, authenticated;
revoke all on function public.correct_employee_wife_record(uuid,bigint,timestamptz,text,bigint,uuid) from public, anon, authenticated;
grant execute on function public.end_employee_wife_marriage(uuid,bigint,timestamptz,date,text,bigint,uuid) to service_role;
grant execute on function public.correct_employee_wife_record(uuid,bigint,timestamptz,text,bigint,uuid) to service_role;
