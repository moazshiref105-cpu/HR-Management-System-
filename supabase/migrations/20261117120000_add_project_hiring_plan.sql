-- Project hiring plans and live staffing calculations.
-- Plans reference existing organization records and never store actual headcount.

create table public.project_hiring_plans (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete restrict,
  department_id bigint not null references public.departments(id) on delete restrict,
  position_id bigint not null references public.positions(id) on delete restrict,
  planned_count integer not null check (planned_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null references public.users(id) on delete restrict,
  updated_by uuid references public.users(id) on delete restrict,
  constraint project_hiring_plans_scope_unique unique (project_id, department_id, position_id)
);

create table public.project_hiring_plan_audit (
  id bigint generated by default as identity primary key,
  plan_id bigint not null,
  actor_id uuid not null references public.users(id) on delete restrict,
  action text not null check (action in ('created','updated','deleted')),
  changed_at timestamptz not null default now(),
  before_state jsonb,
  after_state jsonb
);

create index project_hiring_plans_department_idx on public.project_hiring_plans(department_id);
create index project_hiring_plans_position_idx on public.project_hiring_plans(position_id);
create index project_hiring_plan_audit_history_idx on public.project_hiring_plan_audit(plan_id,changed_at desc,id desc);
create index employees_staffing_active_scope_idx on public.employees(project_id, department_id, position_id)
  where employee_status = 'active';

drop trigger if exists project_hiring_plans_set_updated_at on public.project_hiring_plans;
create trigger project_hiring_plans_set_updated_at
before update on public.project_hiring_plans
for each row execute function public.set_updated_at();

create or replace function public.audit_project_hiring_plan_change()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.project_hiring_plan_audit(plan_id,actor_id,action,after_state)
    values(new.id,new.created_by,'created',to_jsonb(new));
    return new;
  end if;
  insert into public.project_hiring_plan_audit(plan_id,actor_id,action,before_state,after_state)
  values(new.id,coalesce(new.updated_by,new.created_by),'updated',to_jsonb(old),to_jsonb(new));
  return new;
end;
$$;

create trigger project_hiring_plans_audit_change
after insert or update on public.project_hiring_plans
for each row execute function public.audit_project_hiring_plan_change();

create or replace function public.delete_project_hiring_plan(p_plan_id bigint,p_actor_id uuid)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare v_plan public.project_hiring_plans%rowtype;
begin
  if not exists(select 1 from public.users where id=p_actor_id and is_active=true) then
    raise exception 'Active actor user is required';
  end if;
  select * into v_plan from public.project_hiring_plans where id=p_plan_id for update;
  if not found then return false; end if;
  insert into public.project_hiring_plan_audit(plan_id,actor_id,action,before_state)
  values(v_plan.id,p_actor_id,'deleted',to_jsonb(v_plan));
  delete from public.project_hiring_plans where id=v_plan.id;
  return true;
end;
$$;

